const char* JianChuField(int field, int idx, int enc)
{
    if (idx < 0) idx = 0; if (idx > 11) idx = 11;
    bool u8 = (enc == 'u');
    switch (field)
    {
    case 0: return u8 ? (bJianChuTrad ? U8jianchu_tra[idx] : U8jianchu_sim[idx]) : (enc=='g' ? GBjianchu[idx] : B5jianchu[idx]);
    case 1: return u8 ? U8jixiong[idx] : (enc=='g' ? GBjixiong[idx] : B5jixiong[idx]);
    case 2: return u8 ? (bJianChuTrad ? U8hanyi_tra[idx] : U8hanyi_sim[idx]) : (enc=='g' ? GBhanyi[idx] : B5hanyi[idx]);
    case 3: return u8 ? (bJianChuTrad ? U8yi_tra[idx] : U8yi_sim[idx]) : (enc=='g' ? GByi[idx] : B5yi[idx]);
    case 4: return u8 ? (bJianChuTrad ? U8ji_tra[idx] : U8ji_sim[idx]) : (enc=='g' ? GBji[idx] : B5ji[idx]);
    }
    return "";
}

